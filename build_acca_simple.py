MAX_TOPICS_IN_MAP = 9


def load(path):
    with io.open(path, encoding="utf-8") as f:
        return json.load(f)


def build():
    structure = load(os.path.join(PDFTEXT, "acca_foundation_structure.json"))
    installed = load(os.path.join(PDFTEXT, "mindmaps.json"))

    out = {}

    for book in ["acfab", "acfma", "acfbe", "acffa1st"]:
        chapters = structure.get(book, {}).get("chapters", [])
        if not chapters:
            print(f"  {book}: no chapters, skipping")
            continue

        out_ch = []
        for ch in chapters:
            tid = f"{book}-ch{ch['num']}-t1"
            title = ch["title"]

            sec = {"heading": ch["title"], "subsections": []}
            dia = DIA.diagram_for({"heading": ch["title"], "subsections": []}, ch["title"], "definition")
            outline = DIA.build_outline({"heading": ch["title"], "subsections": []}, ch["title"])
            teach = {"what": "", "why": "", "ladder": [], "trap": "", "example": "", "vocab": {}}

            topics = [{
                "id": f"{book}-ch{ch['num']}-t1",
                "num": "1",
                "title": ch["title"],
                "kind": "definition",
                "page": str(ch.get("startPp", "")),
                "diagram": dia,
                "outline": outline,
                "teach": {"what": "", "why": "", "ladder": [], "trap": "", "example": "", "vocab": {}},
            }]

            cmap = DIA.chapter_map(
                {"title": DIA.clean_label(ch["title"], 90)},
                topics, max_branches=9)

            out_ch = [{
                "id": f"{book}-ch{ch['num']}",
                "num": ch["num"],
                "title": ch["title"],
                "pages": str(ch.get("startPp", "")),
                "subject": "ACCA",
                "subjectName": "ACCA Foundation",
                "map": cmap,
                "summary": "",
                "revision": "",
                "topics": topics,
            }]

            print(f"  {book}: 1 chapter built")

    return {"acfab": [], "acfma": [], "acfbe": [], "acffa1st": []}


