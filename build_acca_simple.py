# Books with a mind map. These must stay in step with ACCA_FOUNDATION_BOOKS: a book
# removed from the library must not be listed here, or the next run reaches for a PDF
# that no longer exists and the mind map view offers a subject with no book behind it.
#   "acffa2kit" removed - FA2 practice kit
#   "acfmaprk"  removed - MA2 practice and revision kit
